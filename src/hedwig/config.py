"""Project config: discover folder services and read/write .hedwig.yml."""

from pathlib import Path

import yaml

CONFIG_NAME = ".hedwig.yml"

# manifest file -> (language, guessed test command)
MANIFESTS: dict[str, tuple[str, str]] = {
    "package.json": ("node", "npm test"),
    "Cargo.toml": ("rust", "cargo test"),
    "composer.json": ("php", "vendor/bin/phpunit"),
    "pom.xml": ("java", "mvn -q test"),
    "requirements.txt": ("python", "python -m pytest"),
    "pyproject.toml": ("python", "python -m pytest"),
}

SKIP_DIRS = {"node_modules", "target", "vendor"}

HEADER = """\
# Generated by `hedwig init`. Each folder next to this file is one service.
#
# tier:  critical | high | medium | low
# allow: open_fix_pr, auto_merge_if_verified, rollback, takedown
#
# Optional per-service fields, added when needed:
#   log_path: <service>/logs/access.log
#   port: 3000
#   health_path: /health
#   render_service_id: srv-xxxx
"""


def discover_services(root: Path) -> dict[str, dict]:
    """Every direct subfolder of root holding a supported manifest is one service."""
    services: dict[str, dict] = {}
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        if folder.name.startswith(".") or folder.name in SKIP_DIRS:
            continue
        for manifest, (language, test_cmd) in MANIFESTS.items():
            if (folder / manifest).is_file():
                services[folder.name] = {
                    "language": language,
                    "tier": "medium",
                    "allow": ["open_fix_pr"],
                    "test_cmd": test_cmd,
                }
                break
    return services


def load_project(root: Path) -> dict | None:
    """The parsed .hedwig.yml in root, or None if there isn't one."""
    path = root / CONFIG_NAME
    if not path.is_file():
        return None
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def init_project(root: Path) -> tuple[Path, list[str], list[str]]:
    """Write root/.hedwig.yml. Existing service entries are kept exactly as they are.

    Returns the file path, the services added and the services kept.
    """
    existing = (load_project(root) or {}).get("services") or {}
    found = discover_services(root)
    added = [name for name in found if name not in existing]
    kept = [name for name in existing]
    services = {**existing, **{name: found[name] for name in added}}
    body = yaml.safe_dump({"services": services}, sort_keys=False)
    path = root / CONFIG_NAME
    path.write_text(HEADER + "\n" + body, encoding="utf-8")
    return path, added, kept
